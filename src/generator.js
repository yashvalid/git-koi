/**
 * Renders authentic Nishikigoi body patterns according to breed
 */
function renderKoiPatterns(breed, theme) {
  switch (breed) {
    case 'tancho':
      // Pristine white with round solitary crimson circle on the head
      return `
        <g id="pattern-tancho" filter="url(#glow-effect)">
          <ellipse cx="42" cy="0" rx="9" ry="8" fill="${theme.patternColor}" />
          <ellipse cx="43" cy="-1" rx="6" ry="5" fill="${theme.patternAccent}" />
        </g>`;

    case 'ogon':
      // Gleaming metallic gold with subtle scale accents
      return `
        <g id="pattern-ogon">
          <!-- Metallic Scales & Spine Highlights -->
          <circle cx="28" cy="-5" r="4" fill="${theme.patternAccent}" opacity="0.5" />
          <circle cx="20" cy="6" r="4.5" fill="${theme.patternAccent}" opacity="0.5" />
          <circle cx="8" cy="-8" r="5" fill="${theme.patternAccent}" opacity="0.45" />
          <circle cx="-5" cy="4" r="5" fill="${theme.patternAccent}" opacity="0.5" />
          <circle cx="-18" cy="-4" r="4" fill="${theme.patternAccent}" opacity="0.45" />
          <ellipse cx="32" cy="0" rx="14" ry="4" fill="${theme.patternAlt}" opacity="0.65" />
        </g>`;

    case 'sanke':
      // Vermilion Hi spots + Sumi Black ink spots
      return `
        <g id="pattern-sanke">
          <!-- Head Vermilion Patch -->
          <path d="M 52 -6 C 45 -14, 30 -16, 26 -6 C 24 5, 38 10, 48 4 Z" fill="${theme.patternColor}" />
          <!-- Mid Torso Vermilion -->
          <path d="M 12 -18 C 0 -24, -14 -12, -6 6 C 2 14, 18 2, 12 -18 Z" fill="${theme.patternColor}" />
          <!-- Sumi Ink Black Accents -->
          <ellipse cx="4" cy="14" rx="7" ry="5" fill="${theme.patternAccent}" />
          <ellipse cx="-20" cy="-6" rx="9" ry="4" fill="${theme.patternAccent}" />
          <circle cx="36" cy="8" r="3.5" fill="${theme.patternAccent}" />
        </g>`;

    case 'showa':
      // Black Sumi base with dynamic vermilion and white bolts
      return `
        <g id="pattern-showa">
          <!-- Crimson Lightning Patches -->
          <path d="M 54 -4 C 42 -12, 34 2, 44 8 C 50 10, 56 2, 54 -4 Z" fill="${theme.patternColor}" />
          <path d="M 16 -16 C -2 -22, -10 -4, 2 8 C 12 16, 22 -4, 16 -16 Z" fill="${theme.patternColor}" />
          <!-- Pure White Accents -->
          <path d="M 28 6 C 20 16, 8 18, 12 10 C 18 4, 25 2, 28 6 Z" fill="${theme.patternAccent}" opacity="0.9" />
          <ellipse cx="-16" cy="6" rx="6" ry="4" fill="${theme.patternAccent}" opacity="0.9" />
        </g>`;

    case 'asagi':
      // Blue reticulated netting with vermilion flanks
      return `
        <g id="pattern-asagi">
          <!-- Vermilion Belly & Fin Line Flanks -->
          <path d="M 38 -18 C 15 -25, -15 -22, -32 -10 L -30 -14 C -10 -27, 20 -28, 42 -20 Z" fill="${theme.patternColor}" />
          <path d="M 38 18 C 15 25, -15 22, -32 10 L -30 14 C -10 27, 20 28, 42 20 Z" fill="${theme.patternColor}" />
          <!-- Diamond Netting Scales (Matsuba) -->
          <line x1="25" y1="-10" x2="-25" y2="-10" stroke="${theme.patternAccent}" stroke-width="1.2" stroke-dasharray="2,3" />
          <line x1="30" y1="0" x2="-30" y2="0" stroke="${theme.patternAccent}" stroke-width="1.2" stroke-dasharray="2,3" />
          <line x1="25" y1="10" x2="-25" y2="10" stroke="${theme.patternAccent}" stroke-width="1.2" stroke-dasharray="2,3" />
        </g>`;

    case 'neon':
      // Cyberpunk Tron-like bioluminescent lines
      return `
        <g id="pattern-neon" filter="url(#glow-effect)">
          <path d="M 52 0 L 25 -14 L -20 -10 L -38 0 L -20 10 L 25 14 Z" fill="none" stroke="${theme.patternColor}" stroke-width="2" />
          <circle cx="36" cy="0" r="4.5" fill="${theme.patternAccent}" />
          <circle cx="5" cy="0" r="6" fill="${theme.patternAlt}" />
          <circle cx="-20" cy="0" r="3.5" fill="${theme.patternColor}" />
          <line x1="60" y1="0" x2="-40" y2="0" stroke="#ffffff" stroke-width="1.2" stroke-dasharray="4,2" />
        </g>`;

    case 'kohaku':
    default:
      // Classic 3-step Danmoyo Kohaku (Head, Mid, Tail patches)
      return `
        <g id="pattern-kohaku">
          <!-- Step 1: Head Patch (Menkaburi / Tancho-like oval on brow) -->
          <path d="M 54 -4 C 48 -14, 32 -14, 28 -4 C 24 6, 38 10, 48 6 Z"
                fill="${theme.patternColor}" stroke="${theme.patternAccent}" stroke-width="0.5" />
          <!-- Step 2: Bold Mid-Body Saddle Patch -->
          <path d="M 18 -18 C 2 -24, -12 -16, -6 -2 C -2 12, 14 18, 22 2 C 26 -8, 24 -14, 18 -18 Z"
                fill="${theme.patternColor}" stroke="${theme.patternAccent}" stroke-width="0.5" />
          <!-- Step 3: Peduncle Tail Patch -->
          <path d="M -22 -8 C -28 -10, -38 -4, -36 3 C -34 8, -25 6, -20 -1 Z"
                fill="${theme.patternColor}" stroke="${theme.patternAccent}" stroke-width="0.5" />
        </g>`;
  }
}

